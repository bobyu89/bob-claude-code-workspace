def r_literal(x) -> str:
    """Python value -> R expression. dict -> named list, list -> list (so length-1 stays a list)."""
    if x is None:
        return "NULL"
    if isinstance(x, bool):
        return "TRUE" if x else "FALSE"
    if isinstance(x, int):
        return f"{x}L" if abs(x) < 2**31 else repr(float(x))
    if isinstance(x, float):
        return repr(x) if math.isfinite(x) else "NA_real_"
    if isinstance(x, str):
        return r_string(x)
    if isinstance(x, dict):
        return "list(" + ", ".join(f"{r_string(k)} = {r_literal(v)}" for k, v in x.items()) + ")"
    if isinstance(x, (list, tuple)):
        return "list(" + ", ".join(r_literal(v) for v in x) + ")"
    raise TypeError(f"cannot express {type(x).__name__} in R")


def r_string(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    return f'"{escaped}"'


class REngine(EngineAdapter):
    name = "r"
    script_name = "analysis.R"
    install_hint = "請安裝 R（https://cran.r-project.org/），並確認 `Rscript` 在 PATH 中。"

    def command(self) -> list[str] | None:
        rscript = shutil.which("Rscript")
        return [rscript, "--vanilla"] if rscript else None

    def env(self) -> dict[str, str]:
        # UTF-8 locale so non-ASCII column names (e.g. 前測) are read and written intact.
        return {**super().env(), "LC_ALL": "C.UTF-8", "LANG": "C.UTF-8"}

    def render_script(self, plan: dict, default_data: str) -> str:
        head = (
            PRELUDE.replace("__AISTAT_VERSION__", __version__)
            .replace("__RUN_ID__", plan["run_id"])
            .replace("__METHOD__", plan["method"])
            .replace("__PLAN_R__", r_literal(plan))
            .replace("__DEFAULT_DATA__", r_string(default_data))
        )
        return head + METHOD_CODE[plan["method"]] + FOOTER
