def r_literal(x) -> str:
    """Python value -> R expression. dict -> named list, list -> list (so length-1 stays a list)."""
    if x is None:
        return "NULL"
    if isinstance(x, bool):
        return "TRUE" if x else "FALSE"
    if isinstance(x, int):
        return f"{x}L" if abs(x) < 2**31 else repr(float(x))
    if isinstance(x, float):
        return repr(x) if math.isfinite(x) else "NA_real_"
    if isinstance(x, str):
        return r_string(x)
    if isinstance(x, dict):
        return "list(" + ", ".join(f"{r_string(k)} = {r_literal(v)}" for k, v in x.items()) + ")"
    if isinstance(x, (list, tuple)):
        return "list(" + ", ".join(r_literal(v) for v in x) + ")"
    raise TypeError(f"cannot express {type(x).__name__} in R")


def r_string(s: str) -> str:
    escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    return f'"{escaped}"'


