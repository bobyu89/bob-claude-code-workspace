PRELUDE = r'''# Generated by aistat __AISTAT_VERSION__ for __RUN_ID__ (__METHOD__).
# Re-run from this folder:  Rscript analysis.R [data.csv] [raw_outputs/results.json]
args <- commandArgs(trailingOnly = TRUE)
DATA <- if (length(args) >= 1) args[1] else __DEFAULT_DATA__
OUT <- if (length(args) >= 2) args[2] else "raw_outputs/results.json"
PLAN <- __PLAN_R__
V <- PLAN$variables
O <- PLAN$options

json_str <- function(s) {
  s <- gsub("\\", "\\\\", s, fixed = TRUE)
  s <- gsub("\"", "\\\"", s, fixed = TRUE)
  s <- gsub("\n", "\\n", s, fixed = TRUE)
  s <- gsub("\r", "\\r", s, fixed = TRUE)
  s <- gsub("\t", "\\t", s, fixed = TRUE)
  paste0("\"", enc2utf8(s), "\"")
}

# Named list -> object, unnamed list -> array, length-1 atomic -> scalar.
to_json <- function(x) {
  if (is.null(x)) return("null")
  if (is.list(x)) {
    if (length(x) > 0 && !is.null(names(x))) {
      items <- vapply(seq_along(x), function(i) paste0(json_str(names(x)[i]), ":", to_json(x[[i]])), "")
      return(paste0("{", paste(items, collapse = ","), "}"))
    }
    return(paste0("[", paste(vapply(x, to_json, ""), collapse = ","), "]"))
  }
  if (length(x) != 1) return(to_json(as.list(unname(x))))
  if (is.na(x)) return("null")
  if (is.logical(x)) return(if (x) "true" else "false")
  if (is.numeric(x)) return(if (is.finite(x)) formatC(x, digits = 17, format = "g") else "null")
  json_str(as.character(x))
}

shapiro <- function(values, id, label) {
  base <- list(id = id, label = label, test = "Shapiro-Wilk", n = length(values))
  if (length(values) < 3 || length(values) > 5000 || diff(range(values)) == 0) {
    return(c(base, list(statistic = NULL, p = NULL, violated = NULL, note = "樣本數或變異不足，無法檢定")))
  }
  sw <- shapiro.test(values)
  c(base, list(statistic = unname(sw$statistic), p = sw$p.value, violated = sw$p.value < O$alpha))
}

col_classes <- NA
if (length(PLAN$string_columns) > 0) {
  col_classes <- setNames(rep("character", length(PLAN$string_columns)), unlist(PLAN$string_columns))
}
df <- read.csv(DATA, check.names = FALSE, na.strings = c("", "NA"), encoding = "UTF-8",
               stringsAsFactors = FALSE, colClasses = col_classes)
statistics <- list()
assumptions <- list()
warnings_out <- list()
'''

